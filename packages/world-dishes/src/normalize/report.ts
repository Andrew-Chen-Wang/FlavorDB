import type { WorldDish } from "../types"
import type { Review } from "./quality"

const MARKUP = /\{\{|\}\}|\[\[|\]\]|'''|<[a-z/]/

/** Checks that still flag dishes after cleanup; they're reported, not fixed automatically. */
const CHECKS: [string, (d: WorldDish) => boolean][] = [
  [
    "Markup left in a recipe",
    (d) =>
      d.recipes.some((r) =>
        [...r.steps, ...r.ingredients.map((i) => i.item)].some((s) => MARKUP.test(s)),
      ),
  ],
  ["Recipe with a single ingredient line", (d) => d.recipes.some((r) => r.ingredients.length < 2)],
  [
    "Recipe whose method is under 40 characters",
    (d) => d.recipes.some((r) => r.steps.join("").length < 40),
  ],
  [
    "Recipe with more than 60 lines (several recipes on one page?)",
    (d) => d.recipes.some((r) => r.steps.length + r.ingredients.length > 60),
  ],
  [
    "No recipe, ingredients or description: a name only",
    (d) => !d.recipes.length && !d.ingredients.length && !d.description,
  ],
  ["Not tied to any country", (d) => d.countries.length === 0],
]

function sample<T>(items: T[], n: number, seed = 7): T[] {
  // Deterministic, so the report doesn't change unless the data does.
  const out: T[] = []
  let x = seed
  const pool = [...items]
  while (out.length < n && pool.length) {
    x = (x * 1103515245 + 12345) % 2147483648
    out.push(pool.splice(x % pool.length, 1)[0])
  }
  return out
}

const label = (d: WorldDish) => `${d.name} (\`${d.id}\`)`

export function reviewReport(review: Review): string {
  const lines = [
    "# World dishes: review",
    "",
    "Generated by `pnpm run build-data`. Every imported dish goes through these checks; the first three",
    "sections are fixed automatically, the last is reported for people to look at.",
    "",
    "## Removed",
    "",
    "| Reason | Dishes | Examples |",
    "|---|---:|---|",
    ...[...review.rejected.entries()].map(
      ([reason, list]) =>
        `| ${reason} | ${list.length} | ${sample(list, 4).map(label).join(", ")} |`,
    ),
    "",
    "## Recipes cleaned",
    "",
    `- ${review.recipesCleaned} recipes had leftover wiki markup, table rows, time-only lines ("45 - 60 min") or repeated steps removed.`,
    `- ${review.recipesDropped} recipes had nothing usable left and were dropped.`,
    "",
    "## Duplicates merged",
    "",
    `- ${review.merged} dishes were folded into another with the same name, because their countries and kinds didn't conflict.`,
    "",
    "## Still flagged",
    "",
    "| Check | Dishes | Examples |",
    "|---|---:|---|",
    ...CHECKS.map(([name, test]) => {
      const hits = review.dishes.filter(test)
      return `| ${name} | ${hits.length} | ${sample(hits, 3).map(label).join(", ")} |`
    }),
    "",
  ]
  return lines.join("\n")
}
