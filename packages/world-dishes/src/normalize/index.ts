import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs"
import path from "node:path"
import { CACHE_DIR } from "../fetch/http"
import type { WorldDish } from "../types"
import { loadCookbooks } from "./cookbooks"
import { loadHowToCook } from "./howtocook"
import { mergeDishes } from "./merge"
import { loadWikibooks } from "./wikibooks"
import { loadBranded, loadWikidata } from "./wikidata"
import { reviewDishes } from "./quality"
import { reviewReport } from "./report"

const DATA_DIR = path.join(import.meta.dirname, "..", "..", "data")
const SHARD_SIZE = 2500

const wikidata = loadWikidata(CACHE_DIR)
const wikibooks = loadWikibooks(CACHE_DIR)
const howtocook = loadHowToCook(CACHE_DIR)
const cookbooks = loadCookbooks(CACHE_DIR)
const merged = mergeDishes(wikidata, [...wikibooks, ...howtocook, ...cookbooks])

// Review pass: clean every recipe, drop what isn't a dish, fold duplicates. See data/REVIEW.md.
const review = reviewDishes(merged, loadBranded(CACHE_DIR))
const dishes = review.dishes.toSorted((a, b) => a.id.localeCompare(b.id))

mkdirSync(DATA_DIR, { recursive: true })
for (const f of readdirSync(DATA_DIR)) if (f.endsWith(".jsonl")) rmSync(path.join(DATA_DIR, f))
for (let i = 0; i < dishes.length; i += SHARD_SIZE) {
  const shard = dishes.slice(i, i + SHARD_SIZE)
  const file = path.join(DATA_DIR, `dishes-${String(i / SHARD_SIZE).padStart(2, "0")}.jsonl`)
  writeFileSync(file, `${shard.map((d) => JSON.stringify(d)).join("\n")}\n`)
}

const count = (pred: (d: WorldDish) => boolean) => dishes.filter(pred).length
const countryCounts = new Map<string, number>()
for (const d of dishes)
  for (const c of d.countries) countryCounts.set(c, (countryCounts.get(c) ?? 0) + 1)
const recipes = dishes.reduce((n, d) => n + d.recipes.length, 0)
const stats = [
  "# World dishes: import stats",
  "",
  "Generated by `pnpm run build-data`. Don't edit by hand.",
  "",
  "| | Count |",
  "|---|---:|",
  `| Dishes and foods | ${dishes.length} |`,
  `| …with at least one full recipe | ${count((d) => d.recipes.length > 0)} |`,
  `| …with an ingredient list (recipe or not) | ${count((d) => d.ingredients.length > 0)} |`,
  `| …tied to at least one country | ${count((d) => d.countries.length > 0)} |`,
  `| …with a Chinese name | ${count((d) => !!d.names.zh || /\p{Script=Han}/u.test(d.name))} |`,
  `| Recipe languages | ${[...new Set(dishes.flatMap((d) => d.recipes.map((r) => r.lang)))].join(", ")} |`,
  `| Full recipes | ${recipes} |`,
  `| Countries and territories | ${countryCounts.size} |`,
  "",
  "| Source | Dishes or recipes read | License |",
  "|---|---:|---|",
  `| Wikidata | ${wikidata.length} | CC0 1.0 |`,
  `| Wikibooks Cookbook (English) | ${wikibooks.length} | CC BY-SA 4.0 |`,
  ...(["de", "fr", "es", "it", "ja", "zh", "pt", "ru", "pl", "nl", "hu"] as const).map(
    (lang) =>
      `| Wikibooks cookbook (${lang}) | ${cookbooks.filter((d) => d.recipes[0]?.lang === lang).length} | CC BY-SA 4.0 |`,
  ),
  `| HowToCook | ${howtocook.length} | Unlicense (public domain) |`,
  "",
  "## Top 40 countries",
  "",
  "| Country | Dishes |",
  "|---|---:|",
  ...[...countryCounts.entries()]
    .toSorted((a, b) => b[1] - a[1])
    .slice(0, 40)
    .map(([c, n]) => `| ${c} | ${n} |`),
  "",
].join("\n")
writeFileSync(path.join(DATA_DIR, "STATS.md"), stats)
writeFileSync(path.join(DATA_DIR, "REVIEW.md"), reviewReport(review))
console.log(stats)
