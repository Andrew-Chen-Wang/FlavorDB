/** Finds the countries for a cuisine label such as "Albanian", "Cuisine of Albania" or "Thai cuisine". */
export function countriesForCuisine(label: string): string[] {
  const key = label
    .toLowerCase()
    .replace(/^cuisine of (the )?/, "")
    .replace(/\s+(cuisine|recipes|food)$/, "")
    .trim()
  if (
    /^(us|usa|u\.s\.|united states|us american|southern usa|southern|southern us|new england|midwestern)$/.test(
      key,
    )
  )
    return ["US"]
  return CUISINE_COUNTRIES[key] ?? []
}
